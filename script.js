        //  javascript
//  two types of js 
//  1)vanilla = old (var)
//  2)ES6(ECMA Script 6) = new (let , const) 
// Using var to declare a variable (vanilla , old way)
// var = variable , name = identifier , value = data
// reassign and redeclare were allowed in var
var name = "rehman";
document.write(name);
// using let to declare a variable (ES6 , new way)
// rassign is allowed but redeclare is not allowed in let
let x = "hello world";
document.write(x);
// using const to declare a variable (ES6 , new way)
// reassign and redeclare are not allowed in const
const a = ("hi everyone");
document.write(a);
console.log("hello world!");
// Data types in javascript
// String
let city = "karachi";
console.log(city);
// Number
let age = 18;
console.log(age);
// Boolean
let isStudent = true;
console.log(isStudent);
// bigint
let bigNumber = 12345678901234567890n;
console.log(bigNumber);
// null
